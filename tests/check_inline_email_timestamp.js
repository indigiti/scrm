'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const inline=fs.readFileSync('public_html/static/schoolflow-short-form.js','utf8');
const php=fs.readFileSync('app_private/public_forms.php','utf8');
const app=fs.readFileSync('public_html/static/app.js','utf8');
const css=fs.readFileSync('public_html/static/style.css','utf8');
assert(inline.includes("(mode==='inline'?'<label>Email address"), 'Email input must be inline-only');
assert(inline.includes('type="email" name="email"'), 'Email input must use email type');
assert(inline.includes('autocomplete="email" required'), 'Inline email must be required');
assert(inline.includes("if(mode==='inline'&&(!email"), 'Inline email must be validated before submit');
assert(inline.includes('email:email,phone:phone'), 'Submitted payload must include validated email');
assert(!inline.includes('name="pincode"'), 'Short form must not grow extra fields');
assert(!inline.includes('name="student_name"'), 'Short form must not grow student field');
assert(php.includes("if($email!=='')$email=sf_email($email);"), 'Backend must validate provided emails');
assert(php.includes("$details['email']=$email;"), 'Backend must not discard short-form email');
assert(php.includes("$details['student_name']='';"), 'Missing student name must not be invented');
assert(app.includes('<div class="sf-lead-received" id="sf-contact"><span>Received</span>'), 'Received timestamp must be in summary');
assert(app.includes('<time datetime="${esc(l.created_at)}">'), 'Timestamp should retain original ISO value');
assert(css.includes('.sf-lead-snapshot .sf-lead-received'), 'Lead summary timestamp should be styled');
console.log('PASS: inline-only email, backend storage, short popup compatibility, lead timestamp');
